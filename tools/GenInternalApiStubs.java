import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.lang.reflect.Type;
import java.lang.reflect.TypeVariable;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.StringJoiner;

/**
 * io.papermc.paper.InternalAPIBridge の抽象メソッドを全部「未実装」にするスタブを生成する。
 * paper_api_version を上げて抽象メソッドが増えたら、このスクリプトで再生成する。
 * 使い方: java -cp <paper-api と依存 jar> tools/GenInternalApiStubs.java <出力ファイル>
 */
public final class GenInternalApiStubs {
    /** 手書き側 (OrigamiInternalApiBridge) で実装するメソッド。 */
    private static final String SKIP = "createPluginLifecycleEventManager";

    public static void main(String[] args) throws Exception {
        Class<?> c = Class.forName("io.papermc.paper.InternalAPIBridge");
        List<Method> methods = new ArrayList<>();
        for (Method m : c.getMethods()) {
            if (Modifier.isAbstract(m.getModifiers()) && !m.getName().equals(SKIP)) {
                methods.add(m);
            }
        }
        methods.sort(Comparator.comparing(Method::getName)
                .thenComparing(m -> Arrays.toString(m.getParameterTypes())));

        StringBuilder sb = new StringBuilder();
        sb.append("package io.github.kiyo29.origami.bridge;\n\n");
        sb.append("// GENERATED by tools/GenInternalApiStubs.java. Do not edit by hand.\n");
        sb.append("// paper_api_version を上げたら再生成する。\n");
        sb.append("@SuppressWarnings({\"deprecation\", \"removal\"})\n");
        sb.append("public abstract class InternalApiBridgeStubs implements io.papermc.paper.InternalAPIBridge {\n");
        for (Method m : methods) {
            sb.append('\n').append("    @Override\n    public ");
            TypeVariable<Method>[] tps = m.getTypeParameters();
            if (tps.length > 0) {
                StringJoiner j = new StringJoiner(", ", "<", "> ");
                for (TypeVariable<Method> tp : tps) {
                    Type[] b = tp.getBounds();
                    if (b.length == 1 && b[0] == Object.class) {
                        j.add(tp.getName());
                    } else {
                        StringJoiner bj = new StringJoiner(" & ");
                        for (Type t : b) bj.add(name(t));
                        j.add(tp.getName() + " extends " + bj);
                    }
                }
                sb.append(j);
            }
            sb.append(name(m.getGenericReturnType())).append(' ').append(m.getName()).append('(');
            Type[] pts = m.getGenericParameterTypes();
            for (int i = 0; i < pts.length; i++) {
                String ty = name(pts[i]);
                if (m.isVarArgs() && i == pts.length - 1 && ty.endsWith("[]")) {
                    ty = ty.substring(0, ty.length() - 2) + "...";
                }
                if (i > 0) sb.append(", ");
                sb.append(ty).append(" p").append(i);
            }
            sb.append(')');
            Type[] ex = m.getGenericExceptionTypes();
            if (ex.length > 0) {
                StringJoiner j = new StringJoiner(", ", " throws ", "");
                for (Type t : ex) j.add(name(t));
                sb.append(j);
            }
            StringJoiner sig = new StringJoiner(",");
            for (Class<?> p : m.getParameterTypes()) sig.add(p.getSimpleName());
            sb.append(" {\n        throw io.github.kiyo29.origami.bridge.UnimplementedCalls.exception(\"InternalAPIBridge#")
              .append(m.getName()).append('(').append(sig).append(")\");\n    }\n");
        }
        sb.append("}\n");
        Files.writeString(Path.of(args[0]), sb.toString());
        System.out.println("generated " + methods.size() + " methods -> " + args[0]);
    }

    private static String name(Type t) {
        return t.getTypeName().replace('$', '.');
    }
}
